def _canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, ensure_ascii=False,
                      separators=(",", ":"), allow_nan=False).encode("utf-8")


def _hash(value: Any) -> str:
    return hashlib.sha256(_canonical(value)).hexdigest()


def _valid_sha(value: Any) -> bool:
    return isinstance(value, str) and _SHA.fullmatch(value) is not None


def _abstract_records(data: bytes) -> tuple[dict[str, dict[str, str]], str]:
    try:
        decoded = json.loads(data)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError("PubMed abstract snapshot must be UTF-8 JSON") from exc
    if not isinstance(decoded, dict) or decoded.get("schema") != "g05-pubmed-title-abstract-snapshot-v1":
        raise ValueError("unsupported PubMed title/abstract snapshot schema")
    rows = decoded.get("records")
    if not isinstance(rows, list) or not rows:
        raise ValueError("PubMed snapshot has no records")
    result: dict[str, dict[str, str]] = {}
    for row in rows:
        if not isinstance(row, dict) or set(row) != {
                "pmid", "title", "abstract", "retrieved_at", "source",
                "retrieval_timestamp_basis", "source_response_sha256", "source_record_sha256"}:
            raise ValueError("PubMed snapshot record schema mismatch")
        pmid = str(row["pmid"]).strip()
        title, abstract = row["title"], row["abstract"]
        if (not pmid.isdigit() or not isinstance(title, str) or not title.strip()
                or not isinstance(abstract, str) or not abstract.strip()
                or not isinstance(row["retrieved_at"], str) or not row["retrieved_at"].strip()
                or row["source"] != "NCBI_EUTILS"
                or not isinstance(row["retrieval_timestamp_basis"], str)
                or row["retrieval_timestamp_basis"] not in {
                    "ncbi_capture_manifest", "filesystem_mtime_only"}
                or not _valid_sha(row["source_response_sha256"])
                or not _valid_sha(row["source_record_sha256"])):
            raise ValueError("PubMed snapshot record has incomplete identity or content")
        if pmid in result:
            raise ValueError("duplicate PMID in PubMed title/abstract snapshot")
        expected_record_sha = _hash({k: row[k] for k in row if k != "source_record_sha256"})
        if row["source_record_sha256"] != expected_record_sha:
            raise ValueError("PubMed source record hash mismatch")
        result[pmid] = {"title": title.strip(), "abstract": abstract.strip(),
                        "retrieved_at": row["retrieved_at"],
                        "retrieval_timestamp_basis": row["retrieval_timestamp_basis"],
                        "source_record_sha256": row["source_record_sha256"]}
    return result, hashlib.sha256(data).hexdigest()


def _case_payload(case: dict[str, Any]) -> dict[str, Any]:
    return {key: case[key] for key in ("case_id", "task_id", "source_group_id",
            "source_id", "question", "selected_answer", "evidence")}


def _blind_packets(packet: dict[str, Any], protocol_sha256: str) -> dict[str, dict[str, Any]]:
    rows = []
    for case in packet["cases"]:
        system, user = selected_answer_support_messages(
            case["question"], case["selected_answer"], case["evidence"])
        rows.append({"case_id": case["case_id"], "input_sha256": case["input_sha256"],
                     "system": system, "user": user,
                     "prompt_sha256": hashlib.sha256((system + "\0" + user).encode("utf-8")).hexdigest()})
    packets = {}
    for slot, offset in (("reviewer_a", 0), ("reviewer_b", 1)):
        ordered = list(rows)
        random.Random(int(protocol_sha256[:16], 16) + offset).shuffle(ordered)
        body = {"schema": REFERENCE_PACKET_SCHEMA, "protocol_sha256": protocol_sha256,
                "packet_sha256": packet["packet_sha256"], "reviewer_slot": slot,
                "rubric_sha256": hashlib.sha256(RUBRIC.encode("utf-8")).hexdigest(),
                "instructions": RUBRIC, "cases": ordered}
        body["review_packet_sha256"] = _hash(body)
        packets[slot] = body
    return packets


def build_medaesqa_abstract_bundle(
    source_bytes: bytes, abstract_snapshot_bytes: bytes, *, history_report: dict[str, Any],
    protocol_sha256: str, sample_seed: str, excluded_source_ids: set[str] | list[str],
    reviewer_a: dict[str, str], reviewer_b: dict[str, str], adjudicator: dict[str, str] | None,
    minimum_per_source_stratum: int = 30,
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any], dict[str, Any]]:
    """Build full-abstract target packet, two blinded packets, key and ref plan.

    MedAESQA's native labels are used only to draw provisional acquisition
    strata. They never enter target input, reviewer packets, or AI references.
    """
    if not isinstance(source_bytes, bytes) or not source_bytes:
        raise ValueError("MedAESQA source snapshot must be non-empty bytes")
    if not isinstance(abstract_snapshot_bytes, bytes) or not abstract_snapshot_bytes:
        raise ValueError("complete PubMed title/abstract snapshot is required")
    if (not isinstance(history_report, dict)
            or history_report.get("schema") != "g05-medaesqa-abstract-history-scan-v1"):
        raise ValueError("a frozen full-abstract history report is required")
    source_sha = _raw_sha(source_bytes)
    if history_report.get("source_sha256") != source_sha:
        raise ValueError("history report does not bind the MedAESQA source snapshot")
    abstracts, abstract_sha = _abstract_records(abstract_snapshot_bytes)
    if history_report.get("abstract_snapshot_sha256") != abstract_sha:
        raise ValueError("history report does not bind the PubMed abstract snapshot")
    matched_pmids = history_report.get("matched_pmids")
    matched_qids = history_report.get("matched_question_ids")
    if (not isinstance(matched_pmids, list) or not isinstance(matched_qids, list)
            or any(not str(x).isdigit() for x in matched_pmids)):
        raise ValueError("history report exclusions are malformed")
    if not _valid_sha(protocol_sha256) or not isinstance(sample_seed, str) or not sample_seed.strip():
        raise ValueError("protocol hash and deterministic sampling seed are required")
    if type(minimum_per_source_stratum) is not int or minimum_per_source_stratum < 30:
        raise ValueError("each provisional source stratum must contain at least 30 cases")
    excluded = {str(x) for x in excluded_source_ids} | {str(x) for x in matched_pmids}
    excluded_qids = {str(x) for x in matched_qids}
    candidates, raw_counts, excluded_counts, malformed_counts = _collect_candidates(
        json.loads(source_bytes), excluded_qids)
    selected: dict[str, list[dict[str, str]]] = {"supported": [], "contradicted": [], "insufficient": []}
    used: set[str] = set()
    for native_label in _CLASS_PRIORITY:
        verdict = {"supporting": "supported", "contradicting": "contradicted", "neutral": "insufficient"}[native_label]
        ordered = sorted(candidates[native_label], key=lambda row: hashlib.sha256((
            f"{sample_seed}\0{native_label}\0{row['pmid']}\0{row['question_id']}\0"
            f"{row['model_id']}\0{row['answer_sentence_id']}"
        ).encode("utf-8")).hexdigest())
        for row in ordered:
            pmid = row["pmid"]
            if pmid in used or pmid in excluded or pmid not in abstracts:
                continue
            selected[verdict].append(row)
            used.add(pmid)
            if len(selected[verdict]) == minimum_per_source_stratum:
                break
        if len(selected[verdict]) < minimum_per_source_stratum:
            raise ValueError(f"insufficient new complete-abstract source groups for {verdict}")

    source_binding = _hash({"medaesqa_source_sha256": source_sha,
                            "pubmed_abstract_snapshot_sha256": abstract_sha})
    cases, private_rows = [], []
    label_map = {"supporting": "supported", "contradicting": "contradicted", "neutral": "insufficient"}
    for provisional_class in ("supported", "contradicted", "insufficient"):
        for row in selected[provisional_class]:
            pmid = row["pmid"]
            abstract = abstracts[pmid]
            evidence_text = f"{abstract['title']}\n\n{abstract['abstract']}"
            if len(evidence_text) > MAX_DOC_CHARS:
                raise ValueError(f"complete PubMed title/abstract exceeds the frozen {MAX_DOC_CHARS}-character input contract")
            case_id = "medaesqa-abstract-" + hashlib.sha256(
                f"{protocol_sha256}\0{sample_seed}\0{pmid}\0{row['question_id']}\0{row['answer_sentence_id']}".encode("utf-8")
            ).hexdigest()[:20]
            case = {"case_id": case_id,
                    "task_id": f"{row['question_id']}:{row['model_id']}:{row['answer_sentence_id']}:{pmid}",
                    "source_group_id": pmid, "source_id": pmid,
                    "question": row["question"], "selected_answer": row["answer"],
                    "evidence": [{"doc_id": f"pmid:{pmid}", "text": evidence_text}]}
            cases.append(case)
            private_rows.append({"case_id": case_id, "source_id": pmid,
                "provisional_acquisition_stratum": label_map[row["source_label"]],
                "native_source_label": row["source_label"],
                "native_evidence_excerpt": row["evidence"],
                "native_evidence_excerpt_sha256": _raw_sha(row["evidence"].encode("utf-8")),
                "abstract_record_sha256": abstract["source_record_sha256"],
                "retrieved_at": abstract["retrieved_at"],
                "retrieval_timestamp_basis": abstract["retrieval_timestamp_basis"]})

    packet = seal_selected_answer_packet({
        "schema": PACKET_SCHEMA, "dataset": MEDAESQA_ABSTRACT_DATASET,
        "split": "calibration", "task_contract": TASK_CONTRACT, "scope": SCOPE,
        "source_pool_sha256": source_binding,
        "publication_status_report_sha256": _hash(history_report),
        "sample_plan_sha256": _hash({"seed": sample_seed,
            "minimum_per_source_stratum": minimum_per_source_stratum,
            "excluded_source_ids": sorted(excluded), "source_binding": source_binding}),
        "protocol_sha256": protocol_sha256, "source_id_type": "pmid",
        "source_data_sha256": source_binding, "history_scan_sha256": _hash(history_report),
        "cases": cases,
    })
    packet_counts = validate_selected_answer_packet(packet)
    reviewer_packets = _blind_packets(packet, protocol_sha256)
    if adjudicator is None:
        plan = build_blocked_abstract_reference_plan(packet, reviewer_packets,
            reviewer_a=reviewer_a, reviewer_b=reviewer_b)
    else:
        plan = build_abstract_reference_plan(packet, reviewer_packets,
            reviewer_a=reviewer_a, reviewer_b=reviewer_b, adjudicator=adjudicator)
    private_key = {"schema": "g05-medaesqa-abstract-private-key-v1",
        "packet_sha256": packet["packet_sha256"], "source_pool_sha256": source_binding,
        "rows": private_rows}
    audit = {"schema": "g05-medaesqa-abstract-adapter-audit-v1",
        "dataset": MEDAESQA_ABSTRACT_DATASET, "source_sha256": source_sha,
        "abstract_snapshot_sha256": abstract_sha, "history_report_sha256": _hash(history_report),
        "case_count": packet_counts["case_count"], "source_group_count": packet_counts["source_group_count"],
        "provisional_source_strata": {k: len(v) for k, v in selected.items()},
        "source_relation_counts": dict(raw_counts), "excluded_source_ids": sorted(excluded),
        "excluded_history_question_ids": sorted(excluded_qids),
        "labels_in_target_packet": False, "labels_in_reviewer_packets": False,
        "native_labels_used_for": "provisional_acquisition_stratification_only",
        "reference_origin": ("ai_double_blind_with_third_ai_adjudication" if plan.get("schema") == PLAN_SCHEMA
                             else "ai_reference_plan_blocked_before_dispatch"),
        "reference_plan_status": "frozen" if plan.get("schema") == PLAN_SCHEMA else "blocked",
        "reference_plan_blocker_code": plan.get("blocker_code"),
        "target_context_kind": "complete_pubmed_title_plus_abstract",
        "model_calls": 0, "target_scorer_calls": 0, "dispatch_authorized": False}
    if plan.get("schema") == PLAN_SCHEMA:
        validate_medaesqa_abstract_plan(packet, reviewer_packets, plan)
    else:
        validate_blocked_abstract_reference_plan(packet, reviewer_packets, plan)
    return packet, reviewer_packets, private_key, {"plan": plan, "audit": audit}


def build_blocked_abstract_reference_plan(packet: dict[str, Any],
        reviewer_packets: dict[str, dict[str, Any]], *, reviewer_a: dict[str, str],
        reviewer_b: dict[str, str]) -> dict[str, Any]:
    """Freeze a blocked, non-dispatchable plan when no third free family is verified."""
    validate_selected_answer_packet(packet)
    required = {"provider", "model_id", "model_family"}
    identities = {"A": reviewer_a, "B": reviewer_b}
    if any(not isinstance(v, dict) or set(v) != required
           or any(not isinstance(v[k], str) or not v[k].strip() for k in required)
           for v in identities.values()):
        raise ValueError("two complete independent reviewer identities are required")
    try:
        canon = [_canonical_identity(v["provider"], v["model_id"], v["model_family"])
                 for v in identities.values()]
    except ValueError as exc:
        raise ValueError("reviewer model identities must be in the trusted provider registry") from exc
    if canon[0][1] == canon[1][1] or canon[0][2] == canon[1][2]:
        raise ValueError("blocked plan requires two distinct reviewer models and families")
    if not isinstance(reviewer_packets, dict) or set(reviewer_packets) != {"reviewer_a", "reviewer_b"}:
        raise ValueError("two blinded reviewer packets are required")
    body = {"schema": BLOCKED_PLAN_SCHEMA, "status": "blocked",
        "blocker_code": "third_zero_price_independent_model_family_unverified",
        "blocker": ("Available zero-price evidence verifies Qwen and GLM families only; "
                    "a third distinct trusted family is required for disagreement adjudication."),
        "dataset": MEDAESQA_ABSTRACT_DATASET, "packet_sha256": packet["packet_sha256"],
        "protocol_sha256": packet["protocol_sha256"],
        "reviewer_packet_sha256": {slot: reviewer_packets[slot]["review_packet_sha256"]
                                    for slot in ("reviewer_a", "reviewer_b")},
        "reviewers": identities, "adjudicator": None,
        "model_calls": 0, "dispatch_authorized": False}
    body["plan_sha256"] = _hash(body)
    return body


def validate_blocked_abstract_reference_plan(packet: dict[str, Any],
        reviewer_packets: dict[str, dict[str, Any]], plan: dict[str, Any]) -> dict[str, Any]:
    if (not isinstance(plan, dict) or plan.get("schema") != BLOCKED_PLAN_SCHEMA
            or plan.get("status") != "blocked"
            or plan.get("blocker_code") != "third_zero_price_independent_model_family_unverified"
            or plan.get("packet_sha256") != packet.get("packet_sha256")
            or plan.get("protocol_sha256") != packet.get("protocol_sha256")
            or plan.get("model_calls") != 0 or plan.get("dispatch_authorized") is not False
            or plan.get("adjudicator") is not None
            or plan.get("plan_sha256") != _hash({k: v for k, v in plan.items() if k != "plan_sha256"})):
        raise ValueError("blocked reference plan is malformed or authorizes execution")
    expected = build_blocked_abstract_reference_plan(packet, reviewer_packets,
        reviewer_a=plan.get("reviewers", {}).get("A"),
        reviewer_b=plan.get("reviewers", {}).get("B"))
    if expected != plan:
        raise ValueError("blocked reference plan fields or reviewer packet bindings changed")
    return {"status": "blocked", "model_calls": 0, "dispatch_authorized": False,
            "blocker_code": plan["blocker_code"]}


def build_abstract_reference_plan(packet: dict[str, Any], reviewer_packets: dict[str, dict[str, Any]], *,
                                  reviewer_a: dict[str, str], reviewer_b: dict[str, str],
                                  adjudicator: dict[str, str]) -> dict[str, Any]:
    """Freeze two independent label passes and a separately identified tie-breaker."""
    validate_selected_answer_packet(packet)
    identities = {"reviewer_a": reviewer_a, "reviewer_b": reviewer_b,
                  "adjudicator": adjudicator}
    required = {"provider", "model_id", "model_family"}
    if any(not isinstance(v, dict) or set(v) != required
           or any(not isinstance(v[k], str) or not v[k].strip() for k in required)
           for v in identities.values()):
        raise ValueError("three complete independent AI identities are required")
    try:
        canon = [_canonical_identity(v["provider"], v["model_id"], v["model_family"])
                 for v in identities.values()]
    except ValueError as exc:
        raise ValueError("reviewer model identities must be in the trusted provider registry") from exc
    if len({x[1] for x in canon}) != 3 or len({x[2] for x in canon}) != 3:
        raise ValueError("reviewers and adjudicator must use distinct models and families")
    body = {"schema": PLAN_SCHEMA, "dataset": MEDAESQA_ABSTRACT_DATASET,
        "task_contract": TASK_CONTRACT, "scope": SCOPE,
        "context_kind": "complete_pubmed_title_plus_abstract",
        "packet_sha256": packet["packet_sha256"],
        "protocol_sha256": packet["protocol_sha256"],
        "reviewer_packet_sha256": {slot: reviewer_packets[slot]["review_packet_sha256"]
                                    for slot in ("reviewer_a", "reviewer_b")},
        "rubric_sha256": hashlib.sha256(RUBRIC.encode("utf-8")).hexdigest(),
        "adjudication_rubric_sha256": hashlib.sha256(ADJUDICATION_RUBRIC.encode("utf-8")).hexdigest(),
        "reviewers": {"A": reviewer_a, "B": reviewer_b}, "adjudicator": adjudicator,
        "calls": {"reviewer_a": len(packet["cases"]), "reviewer_b": len(packet["cases"]),
                  "adjudication_max": len(packet["cases"])},
        "max_physical_attempts": 3 * len(packet["cases"]),
        "max_physical_attempts_per_case_per_stage": 1, "retries_per_call": 0,
        "max_cost_usd": "0.00", "cost_policy": "zero_price_only", "paid_fallback": False,
        "model_calls": 0, "dispatch_authorized": False}
    body["plan_sha256"] = _hash(body)
    return body


def validate_medaesqa_abstract_plan(packet: dict[str, Any],
                                    reviewer_packets: dict[str, dict[str, Any]],
                                    plan: dict[str, Any]) -> dict[str, Any]:
    """Validate hash bindings and confirm that blinded packets contain no labels."""
    stats = validate_selected_answer_packet(packet)
    if packet.get("dataset") != MEDAESQA_ABSTRACT_DATASET:
        raise ValueError("full-abstract reference plan requires the new dataset contract")
    if not isinstance(reviewer_packets, dict) or set(reviewer_packets) != {"reviewer_a", "reviewer_b"}:
        raise ValueError("two independent blinded reviewer packets are required")
    expected_ids = {case["case_id"]: case["input_sha256"] for case in packet["cases"]}
    for slot, reviewer_packet in reviewer_packets.items():
        if (not isinstance(reviewer_packet, dict)
                or reviewer_packet.get("schema") != REFERENCE_PACKET_SCHEMA
                or reviewer_packet.get("reviewer_slot") != slot
                or reviewer_packet.get("protocol_sha256") != packet["protocol_sha256"]
                or reviewer_packet.get("packet_sha256") != packet["packet_sha256"]
                or reviewer_packet.get("rubric_sha256") != hashlib.sha256(RUBRIC.encode("utf-8")).hexdigest()
                or reviewer_packet.get("review_packet_sha256") != _hash({k: v for k, v in reviewer_packet.items()
                    if k != "review_packet_sha256"})):
            raise ValueError("blinded reviewer packet identity or hash mismatch")
        rows = reviewer_packet.get("cases")
        if not isinstance(rows, list) or {r.get("case_id"): r.get("input_sha256") for r in rows} != expected_ids:
            raise ValueError("reviewer packet coverage or input binding mismatch")
        for row in rows:
            if _FORBIDDEN & {k.casefold() for k in row}:
                raise ValueError("native source labels leaked into blinded packet")
    if (not isinstance(plan, dict) or plan.get("schema") != PLAN_SCHEMA
            or plan.get("packet_sha256") != packet["packet_sha256"]
            or plan.get("protocol_sha256") != packet["protocol_sha256"]
            or plan.get("reviewer_packet_sha256") != {k: v["review_packet_sha256"] for k, v in reviewer_packets.items()}
            or plan.get("model_calls") != 0 or plan.get("dispatch_authorized") is not False
            or plan.get("paid_fallback") is not False or plan.get("retries_per_call") != 0
            or plan.get("plan_sha256") != _hash({k: v for k, v in plan.items() if k != "plan_sha256"})):
        raise ValueError("AI reference plan is stale, malformed, or authorizes execution")
    expected_plan = build_abstract_reference_plan(packet, reviewer_packets,
        reviewer_a=plan.get("reviewers", {}).get("A"),
        reviewer_b=plan.get("reviewers", {}).get("B"),
        adjudicator=plan.get("adjudicator"))
    if expected_plan != plan:
        raise ValueError("AI reference plan fields do not match the frozen per-case budget and reviewer identities")
    return {**stats, "plan_sha256": plan["plan_sha256"], "model_calls": 0,
            "dispatch_authorized": False}


def validate_medaesqa_abstract_ai_reference(packet: dict[str, Any], reference: dict[str, Any],
                                             plan: dict[str, Any]) -> dict[str, Any]:
    """Validate the frozen AI-reviewed reference; source-native labels cannot pass."""
    if packet.get("dataset") != MEDAESQA_ABSTRACT_DATASET or reference.get("annotation_origin") != "ai":
        raise ValueError("full-abstract reference must be independently AI annotated")
    if reference.get("schema") != REFERENCE_SCHEMA:
        raise ValueError("MedAESQA native citation labels are not valid full-abstract references")
    if (not isinstance(plan, dict) or plan.get("schema") != PLAN_SCHEMA
            or plan.get("packet_sha256") != packet.get("packet_sha256")
            or plan.get("plan_sha256") != _hash({k: v for k, v in plan.items() if k != "plan_sha256"})):
        raise ValueError("AI reference does not bind a valid full-abstract annotation plan")
    stats = validate_selected_answer_reference(packet, reference)
    expected_reviewers = plan.get("reviewers", {})
    provenance = {row["reviewer_id"]: row for row in reference["reviewer_provenance"]}
    for reviewer_id in ("A", "B"):
        planned = expected_reviewers.get(reviewer_id)
        actual = provenance.get(reviewer_id)
        if (not isinstance(planned, dict) or not isinstance(actual, dict)
                or any(actual.get(key) != planned.get(key)
                       for key in ("provider", "model_id", "model_family"))):
            raise ValueError("AI reference reviewer identity differs from its frozen plan")
    planned_adjudicator = plan.get("adjudicator")
    for row in reference["per_case"]:
        adjudication = row["adjudication"]
        if adjudication is not None and any(adjudication.get(key) != planned_adjudicator.get(key)
                for key in ("provider", "model_id", "model_family")):
            raise ValueError("AI adjudicator identity differs from its frozen plan")
    return stats


def build_abstract_source_native_reference(packet: dict[str, Any],
                                           source_cohort: list[dict[str, Any]]) -> dict[str, Any]:
    """Bind MedAESQA's native citation assessments to the full-abstract packet.

    This path is deliberately separate from the AI double-blind plan.  The
    upstream relation label is retained as a citation-assessment reference and
    never presented as an AI or full-abstract human gold label.
    """
    validate_selected_answer_packet(packet)
    if packet.get("dataset") != MEDAESQA_ABSTRACT_DATASET:
        raise ValueError("source-native abstract reference requires the full-abstract dataset")
    if not isinstance(source_cohort, list) or not source_cohort:
        raise ValueError("MedAESQA source cohort is required")
    by_pmid: dict[str, dict[str, str]] = {}
    for row in source_cohort:
        if not isinstance(row, dict) or not isinstance(row.get("question_id"), str):
            raise ValueError("source cohort question identity is malformed")
        answers = row.get("machine_generated_answers")
        if not isinstance(answers, dict):
            raise ValueError("source cohort answer records are malformed")
        for model_id, answer in answers.items():
            for sentence in (answer.get("answer_sentences") or []):
                if not isinstance(sentence, dict):
                    continue
                answer_text = sentence.get("answer_sentence")
                for citation in (sentence.get("citation_assessment") or []):
                    if not isinstance(citation, dict):
                        continue
                    label = citation.get("evidence_relation")
                    pmid = str(citation.get("cited_pmid") or "").strip()
                    excerpt = citation.get("evidence_support")
                    if (label not in MEDAESQA_LABEL_MAP or not pmid.isdigit()
                            or not isinstance(answer_text, str) or not answer_text.strip()
                            or not isinstance(excerpt, str) or not excerpt.strip()):
                        continue
                    if pmid in by_pmid:
                        raise ValueError("source cohort has duplicate PMID citation rows")
                    by_pmid[pmid] = {
                        "question_id": row["question_id"], "model_id": str(model_id),
                        "answer_sentence_id": str(sentence.get("answer_sentence_id") or ""),
                        "answer": answer_text.strip(), "source_label": label,
                        "evidence": excerpt.strip(),
                    }
    rows = []
    for case in packet["cases"]:
        native = by_pmid.get(str(case.get("source_id")))
        if native is None or native["answer"] != case["selected_answer"]:
            raise ValueError("source-native citation does not bind the packet selected answer")
        abstract = str(case["evidence"][0]["text"])
        excerpt = native["evidence"]
        exact = excerpt in abstract
        normalized_abstract = re.sub(r"\s+", " ", html.unescape(abstract)).strip()
        normalized_excerpt = re.sub(r"\s+", " ", html.unescape(excerpt)).strip()
        normalized = normalized_excerpt in normalized_abstract
        if not exact and not normalized:
            raise ValueError("source-native evidence excerpt is absent from the bound abstract")
        annotation = {
            "question_id": native["question_id"],
            "model_id": native["model_id"],
            "answer_sentence_id": native["answer_sentence_id"],
            "pmid": str(case["source_id"]),
            "source_label": native["source_label"],
            "answer_sha256": hashlib.sha256(case["selected_answer"].encode("utf-8")).hexdigest(),
            "evidence_sha256": hashlib.sha256(excerpt.encode("utf-8")).hexdigest(),
            "abstract_sha256": hashlib.sha256(abstract.encode("utf-8")).hexdigest(),
            "excerpt_match_mode": "exact" if exact else "html_entity_normalized",
        }
        source_label = native["source_label"]
        rows.append({
            "case_id": case["case_id"],
            "source_group_id": case["source_group_id"],
            "input_sha256": case["input_sha256"],
            "source_label": source_label,
            "resolved_verdict": MEDAESQA_LABEL_MAP[source_label],
            "resolved_sentence_ids": [0],
            "source_annotation": annotation,
            "source_annotation_sha256": _sha(annotation),
        })
    reference = {
        "schema": ABSTRACT_SOURCE_NATIVE_REFERENCE_SCHEMA,
        "annotation_origin": "source_native_citation_assessment",
        "task_contract": TASK_CONTRACT, "scope": SCOPE,
        "packet_sha256": packet["packet_sha256"],
        "protocol_sha256": packet["protocol_sha256"],
        "source_data_sha256": packet["source_data_sha256"],
        "history_scan_sha256": packet["history_scan_sha256"],
        "label_mapping_sha256": _sha(MEDAESQA_LABEL_MAP),
        "reference_scope": "citation_excerpt_bound_to_full_abstract",
        "per_case": rows,
    }
    from ..eval.grounding_selected_answer_calibration import (
        validate_selected_answer_reference,
    )
    reference["reference_sha256"] = _sha(reference)
    validate_selected_answer_reference(packet, reference)
    return reference


